import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LORE_TRAILER_KEYS } from '../../src/util/constants.js';

/**
 * The agent instruction files in skills/ ship in the npm package and repeat the
 * commit schema by hand. These checks keep them in step with the CLI.
 */
const __dirname = dirname(fileURLToPath(import.meta.url));
const skillsDir = resolve(__dirname, '..', '..', 'skills');
const adaptersDir = join(skillsDir, 'adapters');

const instructionFiles = [
  join(skillsDir, 'lore-agent-instructions.md'),
  ...readdirSync(adaptersDir).map((name) => join(adaptersDir, name)),
];

/** Lore-id is generated by `lore commit`, so the files tell agents not to write it. */
const AUTHORED_TRAILER_KEYS = LORE_TRAILER_KEYS.filter((key) => key !== 'Lore-id');

describe.each(instructionFiles.map((path) => [path.slice(skillsDir.length + 1), path]))(
  'skills/%s',
  (_name, path) => {
    const content = readFileSync(path, 'utf-8');

    it('documents every trailer an agent can write', () => {
      const missing = AUTHORED_TRAILER_KEYS.filter((key) => !content.includes(key));
      expect(missing).toEqual([]);
    });

    it('never pipes commit JSON through echo (an apostrophe breaks the shell string)', () => {
      expect(content).not.toMatch(/echo\s+'\{/);
    });

    it('never uses the validate --since flag removed in v0.8.0', () => {
      expect(content).not.toMatch(/validate[^\n]*--since/);
    });

    it('tells agents to put extra trailers such as Co-Authored-By inside trailers', () => {
      expect(content).toContain('Co-Authored-By');
    });
  },
);
